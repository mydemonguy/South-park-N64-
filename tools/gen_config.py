"""Write the [patches] section of southpark.us.toml from the symbol file.

Usage: python3 -I gen_config.py <rom.z64> <syms.toml> <symbol_lists.cpp> <config.toml>

  * Functions named in N64Recomp's reimplemented/ignored lists are handled by
    N64Recomp itself (replaced by the runtime), so nothing is written for them.
  * sp_* functions are South Park runtime implementations (src/game/southpark_os.cpp):
    listed as `ignored` so N64Recomp doesn't emit them and callers link to ours.
  * Any other function that uses CP0 / TLB / cache / eret instructions can't be
    recompiled and is stubbed.
"""
import re
import struct
import sys

import rabbitizer

CP0_PREFIXES = ("cpu_mfc0", "cpu_mtc0", "cpu_tlb", "cpu_eret", "cpu_cache")

rom = open(sys.argv[1], "rb").read()
syms = open(sys.argv[2]).read()
lists_src = open(sys.argv[3]).read()
config_path = sys.argv[4]

handled = set()
for lst in ("reimplemented_funcs", "ignored_funcs"):
    body = re.search(lst + r"\s*\{(.*?)\};", lists_src, re.S).group(1)
    handled.update(re.findall(r'"(\w+)"', body))

stubs, custom = [], []
pat = r'name = "(\w+)"\nrom = (0x\w+)\nvram = (0x\w+)\nsize = 0x\w+\nfunctions = \[(.*?)\n\]'
for sec, r, v, body in re.findall(pat, syms, re.S):
    r, v = int(r, 16), int(v, 16)
    for name, fv, fs in re.findall(r'name = "(\w+)", vram = (0x\w+), size = (0x\w+)', body):
        fv, fs = int(fv, 16), int(fs, 16)
        if name.startswith("sp_"):
            custom.append(name)
            continue
        if name in handled or name in ("entrypoint_stub",):
            continue
        uses_cp0 = False
        for i in range(0, fs, 4):
            o = fv - v + r + i
            ins = rabbitizer.Instruction(struct.unpack_from(">I", rom, o)[0], fv + i)
            if ins.uniqueId.name.startswith(CP0_PREFIXES):
                uses_cp0 = True
                break
        if uses_cp0:
            stubs.append(name)

stubs.append("func_00410E74")  # orphaned 4-byte `j` before func_00410E78, never called

text = open(config_path).read()
head = text.split("[patches]")[0].rstrip() + "\n\n"
out = head + "[patches]\n"
out += "# Generated by tools/gen_config.py.\n"
out += "# South Park runtime implementations (src/game/southpark_os.cpp): not emitted, callers link to ours.\n"
out += "ignored = [\n" + "".join(f'    "{n}",\n' for n in sorted(set(custom))) + "]\n\n"
out += "# Unnamed code that uses CP0/TLB/cache instructions and can't be recompiled.\n"
out += "stubs = [\n" + "".join(f'    "{n}",\n' for n in sorted(set(stubs))) + "]\n\n"
out += "# Blank out the boot stub's TLB writes (it still jumps to game_boot afterwards) and the\n"
out += "# `break` after that call, which is reached here because the call returns once the game's\n"
out += "# threads are running.\n"
for vram in (0x80000434, 0x80000438, 0x80000440, 0x80000444, 0x80000448, 0x80000450, 0x80000464, 0x800004AC):
    out += f'[[patches.instruction]]\nfunc = "recomp_entrypoint"\nvram = 0x{vram:08X}\nvalue = 0x00000000\n\n'
out += """# game_boot copies the 1 MB boot image itself by polling PI_STATUS and reading the
# cartridge through KSEG1 (0xB0001000), neither of which is mapped. The runtime has
# already loaded exactly that image before calling the entry point, so branch over the
# copy loop to the BSS clear: 0x0022BD10 = b 0x0022BD44.
[[patches.instruction]]
func = "game_boot"
vram = 0x0022BD10
value = 0x1000000C

"""
out += """# func_00404D24 starts with `j 0x00405D38` into the tail of another function
# (jr ra / v0 = 0). Rewrite it in place with identical behavior.
[[patches.instruction]]
func = "func_00404D24"
vram = 0x00404D24
value = 0x00001021   # addu v0, zero, zero

[[patches.instruction]]
func = "func_00404D24"
vram = 0x00404D28
value = 0x03E00008   # jr ra

[[patches.instruction]]
func = "func_00404D24"
vram = 0x00404D2C
value = 0x27BDFFE8   # addiu sp, sp, -0x18 (delay slot, as in the original)

# Demand paging: the VM manager's region create (func_00290FAC, new node in $t0) and
# free (func_00290EAC, unlinked node in $s0) tell the runtime, which pages regions in
# from its SIGSEGV handler and must drop them when a virtual range is reused.
[[patches.hook]]
func = "func_00290FAC"
before_vram = 0x00291050
text = "southpark_vm_region_changed(rdram, (uint32_t)ctx->r8, 0);"

[[patches.hook]]
func = "func_00290EAC"
before_vram = 0x00290F10
text = "southpark_vm_region_changed(rdram, (uint32_t)ctx->r16, 1);"

# Scheduler: __scHandleRSP / __scHandleRDP dereference sc->curRSPTask / curRDPTask
# unchecked; ignore (and log) a done message that arrives with no task running.
[[patches.hook]]
func = "func_00258134"
text = "if (southpark_sched_guard(rdram, ctx, 0)) return;"

[[patches.hook]]
func = "func_00258618"
text = "if (southpark_sched_guard(rdram, ctx, 1)) return;"

[[patches.hook]]
func = "func_00258F40"
text = "southpark_sched_trace(rdram, ctx);"
"""
open(config_path, "w").write(out)
print(f"{len(set(custom))} custom (ignored), {len(set(stubs))} stubbed")
